// 加载中国和老挝地图GeoJSON数据
let mapsLoaded = false

export async function loadChinaMap(echarts) {
  if (mapsLoaded) return true

  try {
    // 从本地加载中国地图和老挝边界数据
    const [chinaRes, laosRes] = await Promise.all([
      fetch('/maps/china.json'),
      fetch('/maps/laos.json')
    ])

    const chinaGeoJson = await chinaRes.json()
    const laosGeoJson = await laosRes.json()

    // 合并中国和老挝地图
    const combinedGeoJson = {
      type: 'FeatureCollection',
      features: [...chinaGeoJson.features, ...laosGeoJson.features]
    }

    echarts.registerMap('china', combinedGeoJson)
    mapsLoaded = true
    return true
  } catch (error) {
    console.error('加载地图数据失败:', error)
    return false
  }
}

